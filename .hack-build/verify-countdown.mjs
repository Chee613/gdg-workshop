import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1280,height:720},reducedMotion:'reduce'}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
 await page.addInitScript(()=>{const read=Date.now;window.clockTestOffset=0;Date.now=()=>read()+window.clockTestOffset;});
 await page.goto((process.env.PREVIEW_URL||'http://127.0.0.1:8777')+'/Hackathon-Tips.html?preview=timer#timer');
 const clock=page.locator('[data-countdown]'),face=clock.getByRole('timer');
 await page.waitForSelector('[data-countdown][data-state="ready"]');
 await page.waitForSelector('#arcade-dino[data-clock-runner="true"]');
 const runner=page.locator('#arcade-dino'),position=()=>runner.evaluate(image=>image.getBoundingClientRect().x);
 assert.ok(Math.abs(await position()-40)<1,'Dinosaur starts on the left');
 assert.equal(await runner.evaluate(image=>image.getAnimations()[0].effect.getTiming().duration),300000);
 assert.equal(await face.textContent(),'05:00');
 const names=await page.locator('.slide').evaluateAll(slides=>slides.map(slide=>slide.getAttribute('aria-label')));
 assert.deepEqual(names.slice(-3),['Criteria','Timer','Thanks']);
 await clock.getByRole('button',{name:'Start',exact:true}).click();
 assert.equal(await page.locator('.slide.active').getAttribute('aria-label'),'Timer');
 await page.evaluate(()=>window.clockTestOffset+=61000);
 await page.waitForFunction(()=>document.querySelector('[role="timer"]').textContent==='03:59');
 assert.ok(await position()>270&&await position()<285,'Dinosaur position follows the same five-minute clock');
 await page.locator('.stage').screenshot({path:'.hack-build/gdg-clock-running.png'});
 await clock.getByRole('button',{name:'Pause',exact:true}).click();
 const held=await face.textContent();
 const heldX=await position();
 await page.evaluate(()=>window.clockTestOffset+=600000);await page.waitForTimeout(300);
 assert.equal(await face.textContent(),held,'Pause preserves remaining time');
 assert.ok(Math.abs(await position()-heldX)<.1,'Pause also freezes the dinosaur');
 await clock.getByRole('button',{name:'Resume',exact:true}).click();
 await page.evaluate(()=>window.clockTestOffset+=240000);
 await page.waitForSelector('[data-countdown][data-state="done"]');
 assert.equal(await face.textContent(),'00:00');
 assert.ok(Math.abs((await runner.boundingBox()).x+(await runner.boundingBox()).width-1240)<1,'Dinosaur reaches the right at zero');
 assert.equal(await clock.getByRole('status').textContent(),'Time’s up');
 assert.equal(await page.locator('.slide.active').getAttribute('aria-label'),'Timer','Finishing does not change slides');
 await clock.getByRole('button',{name:'Restart',exact:true}).click();
 await clock.getByRole('button',{name:'Reset',exact:true}).click();
 assert.equal(await face.textContent(),'05:00');assert.equal(await clock.getAttribute('data-state'),'ready');
 assert.ok(Math.abs(await position()-40)<1,'Reset returns the dinosaur to the left');
 await page.evaluate(()=>document.fonts.ready);
 await page.locator('.stage').screenshot({path:'.hack-build/gdg-clock-desktop.png'});
 await clock.getByRole('button',{name:'Start',exact:true}).click();
 await page.getByRole('button',{name:'Go directly to Thanks',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('#arcade-dino').hasAttribute('data-clock-runner'));
 assert.equal(await runner.evaluate(image=>image.getAnimations().length),0,'Other slides retain their own dinosaur motion');
 await page.evaluate(()=>window.clockTestOffset+=10000);
 await page.getByRole('button',{name:'Go directly to Timer',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[role="timer"]').textContent!=='05:00');
 assert.equal(await clock.getAttribute('data-state'),'running','Navigation preserves the timer');
 assert.ok(await position()>75,'Returning restores the elapsed dinosaur position');
 await clock.getByRole('button',{name:'Reset',exact:true}).click();
 await page.emulateMedia({reducedMotion:'no-preference'});
 await clock.getByRole('button',{name:'Start',exact:true}).click();
 const sprite=await runner.getAttribute('src');
 await page.waitForFunction(before=>document.querySelector('#arcade-dino').getAttribute('src')!==before,sprite);
 await clock.getByRole('button',{name:'Reset',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.waitForFunction(()=>document.body.dataset.layout==='portrait');
 const bounds=await clock.boundingBox();
 assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390&&bounds.y+bounds.height<=844);
 const dinoBounds=await runner.boundingBox();
 assert.ok(dinoBounds.x>=0&&dinoBounds.x+dinoBounds.width<=390&&dinoBounds.y+dinoBounds.height<=844,'Phone dinosaur stays inside the slide');
 for(const button of await clock.getByRole('button').all())assert.ok((await button.boundingBox()).height>=43.5);
 await page.screenshot({path:'.hack-build/gdg-clock-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log('Passed: synchronized five-minute dinosaur run, pause/resume/reset, running sprites, navigation, background timing and mobile fit.');
}finally{await browser.close();}
